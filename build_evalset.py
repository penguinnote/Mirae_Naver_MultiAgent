"""
연금 Agent 평가셋 생성 스크립트

권인근님이 정리한 6개 질의 유형(세제 / 과세·세율 / 상품 필터링 / 법적 권리·압류 /
제도 비교 / 절세·복합 상담)을 뼈대로, 실제 chunks_final.jsonl과 fund_fees.sqlite에
근거가 있는 문항만 골라 평가셋을 만든다.

각 문항 스키마
--------------
  question_id        Q-001 …
  question           평가 질의 원문 (평가 API에 그대로 넣을 수 있는 형태)
  query_type         6개 유형 중 하나
  difficulty         하 / 중 / 상
  engine             vector | sql | hybrid   ← 어느 도구가 답해야 하는가
  answer_points      정답에 반드시 들어가야 하는 핵심 사실 (문자열 리스트)
                     → 채점 시 answer 안에 이 문자열들이 있는지로 자동 1차 채점
  expected_chunks    정답 근거 청크 ID (검색 Recall@k 측정용)
  expected_sql       engine=sql일 때 참고 SQL (정답 자체가 아니라 "이렇게 뽑으면 된다")
  trap               이 문항이 노리는 함정 / 오답 유형
  source_doc         근거 문서
  engine_only        True면 검색 채점에서 제외 (SQL/계산으로만 풀리는 문항).
                     문서에 답이 통문장으로 없는 집계·계산 질의가 여기 해당한다.
  wrong_markers      답변에 이 문구가 있으면 오답 가능성이 높다는 경고 패턴.
                     자동 실패 처리는 하지 않고 사람이 보라고 표시만 한다.

주의
----
answer_points는 "이 문자열이 답변에 있어야 한다"는 뜻이지, 답변이 이 문자열만
있으면 된다는 뜻이 아니다. 자동 채점은 1차 필터일 뿐이고, 최종 판단은 사람이 한다.
숫자는 표기 흔들림(900만원 / 900만 원 / 9,000,000)을 고려해 여러 변형을 넣었다.
"""
from __future__ import annotations
import json
from pathlib import Path

EVAL = []


def q(qid, question, query_type, difficulty, engine, answer_points,
      expected_chunks=None, expected_sql=None, trap="", source_doc="",
      engine_only=False, wrong_markers=None):
    EVAL.append({
        "engine_only": engine_only,
        "wrong_markers": wrong_markers or [],
        "question_id": qid,
        "question": question,
        "query_type": query_type,
        "difficulty": difficulty,
        "engine": engine,
        "answer_points": answer_points,
        "expected_chunks": expected_chunks or [],
        "expected_sql": expected_sql,
        "trap": trap,
        "source_doc": source_doc,
    })


