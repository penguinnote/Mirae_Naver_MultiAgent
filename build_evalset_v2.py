    cov = collections.Counter(e["coverage"] for e in EVAL)
    print(f"평가셋 v2 — {len(EVAL)}문항 → {out}")
    print(f"  커버리지: full {cov['full']} / partial {cov['partial']} / none {cov['none']}")
